#!/usr/bin/env python3
"""Generate AxiomCheck.lean: `#print axioms` for every ✱2–✱5 theorem, `complete`, and every theorem of
the ✱9–✱21 files, the rule and style modules, the models, the order checker and the
degenerate-family examples. Run `lake env lean AxiomCheck.lean`; every line should say "does not depend on
any axioms", except the declarations listed in README.md (Status)."""
import re, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
names = []
for f in ["PM/Replay.lean", "PM/Replay2.lean"]:
    names += [f"PM.{n}" for n in re.findall(r"^theorem (t[2-5]_\w+)", (root / f).read_text(), re.M)]
names.append("PM.complete")
THM = r"^(?:private )?theorem ([\w.']+)"
DEF = r"^(?:noncomputable )?(?:def|abbrev) ([\w.]+)"
names += [f"PM.QL.{n}" for n in re.findall(r"^theorem (\w+)", (root / "PM/QuantLift.lean").read_text(), re.M)]
files = ["PM/Quant.lean", "PM/Rules/Comprehension.lean", "PM/Rules/Reducibility.lean", "PM/Systems.lean"]
files += sorted(str(p.relative_to(root)) for p in (root / "PM/Pred").glob("*.lean"))
files += sorted(str(p.relative_to(root)) for p in (root / "PM/Models").glob("*.lean"))
files += ["PM/Star10.lean", "PM/Chain.lean", "PM/Star11.lean", "PM/Star12.lean", "PM/Star13.lean", "PM/Star14.lean",
          "PM/Star20.lean", "PM/Star21.lean", "PM/Orders.lean", "PM/Trap.lean"]
files += sorted(str(p.relative_to(root)) for p in root.glob("PM/Styles*.lean"))
for f in files:
    p = root / f
    if not p.exists():
        continue
    text = p.read_text()
    names += [f"PM.{n}" for n in re.findall(THM, text, re.M) if not text.count(f"private theorem {n}")]
    names += [f"PM.{n}" for n in re.findall(DEF, text, re.M) if "Model" in n or "model" in n.lower()]
seen = set(); uniq = []
for n in names:
    if n not in seen:
        seen.add(n); uniq.append(n)
out = ["-- Generated by data/gen_axiomcheck.py; run with `lake env lean AxiomCheck.lean`.", "import PM", ""]
out += [f"#print axioms {n}" for n in uniq]
(root / "AxiomCheck.lean").write_text("\n".join(out) + "\n")
print(len(uniq), "names")
