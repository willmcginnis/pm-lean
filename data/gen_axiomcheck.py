#!/usr/bin/env python3
"""Generate AxiomCheck.lean: `#print axioms` for every ✱2–✱5 theorem, `complete`, and every theorem of
the ✱9–✱11 files. Run `lake env lean AxiomCheck.lean`; every line should say
"does not depend on any axioms"."""
import re, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
names = []
for f in ["PM/Replay.lean", "PM/Replay2.lean"]:
    names += [f"PM.{n}" for n in re.findall(r"^theorem (t[2-5]_\w+)", (root / f).read_text(), re.M)]
names.append("PM.complete")
for n in re.findall(r"^theorem (\w+)", (root / "PM/Quant.lean").read_text(), re.M):
    names.append(f"PM.{n}")
names += ["PM.twoModel", "PM.emptyModel"]
names += [f"PM.QL.{n}" for n in re.findall(r"^theorem (\w+)", (root / "PM/QuantLift.lean").read_text(), re.M)]
for f in ["PM/Star10.lean", "PM/Star11.lean"]:
    names += [f"PM.{n}" for n in re.findall(r"^theorem (\w+)", (root / f).read_text(), re.M)]
out = ["-- Generated by data/gen_axiomcheck.py; run with `lake env lean AxiomCheck.lean`.", "import PM", ""]
out += [f"#print axioms {n}" for n in names]
(root / "AxiomCheck.lean").write_text("\n".join(out) + "\n")
print(len(names), "names")
