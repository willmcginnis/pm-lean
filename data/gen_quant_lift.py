#!/usr/bin/env python3
"""Generate PM/QuantLift.lean: every ✱2–✱5 theorem of PM/Replay*.lean, restated for ✱10 formulas
(QF V, over any variable family V : Ty → Type) and proved by `liftThm` (PM/Quant.lean). The statement text is copied from PM/Statements.lean,
with F.imp/F.and/F.iff renamed to QF.imp/QF.and/QF.iff; Lean checks that it is the lifted formula."""
import re, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
stmts = (root / "PM/Statements.lean").read_text()
proved = set(re.findall(r"^theorem (t[2-5]_\w+)", (root / "PM/Replay.lean").read_text()
                        + (root / "PM/Replay2.lean").read_text(), re.M))

out = ["-- Generated by data/gen_quant_lift.py; do not edit.",
       "import PM.Quant", "import PM.Replay", "import PM.Replay2",
       "/-!", "  ✱1–✱5 for propositions containing apparent variables (✱10, p. 144): each ✱2–✱5 theorem,",
       "  with its propositional variables replaced by arbitrary ✱10 formulas. `PM.QL.t2_05 p q r` is",
       "  `PM.t2_05` lifted by `liftThm`; the statement is checked by Lean against the lifted formula.", "-/",
       "namespace PM.QL", "open PM", ""]
n = 0
for m in re.finditer(r"^/-- \*(\S+) -/\ndef s(\w+) ((?:\(\w+ : F\) )*): F := (.*)$", stmts, re.M):
    pid, name, params, body = m.groups()
    if f"t{name}" not in proved:
        continue
    vs = re.findall(r"\((\w+) : F\)", params)
    assert set(vs) <= {"p", "q", "r", "s"}, (name, vs)
    body = body.replace("F.imp", "QF.imp").replace("F.and", "QF.and").replace("F.iff", "QF.iff")
    get = lambda v: v if v in vs else vs[0]
    args = " ".join(f'(.var "{v}")' for v in vs)
    out.append(f"/-- ✱{pid.replace('.', '·')} -/")
    out.append(f"theorem t{name} {{V : Ty → Type}} {{S : Sys}} {' '.join(f'({v} : QF V)' for v in vs)} : QThm S ({body}) :=")
    out.append(f"  liftThm (_root_.PM.t{name} {args}) (subst4 {get('p')} {get('q')} {get('r')} {get('s')})")
    n += 1
out += ["", "end PM.QL", ""]
(root / "PM/QuantLift.lean").write_text("\n".join(out))
print(n, "theorems lifted")
