#!/usr/bin/env python3
"""Generate AxiomCheck.lean: `#print axioms` for every public theorem of every file under PM/ (✱1–✱5,
`complete`, ✱9–✱22, ✱9's own foundation in PM/Found9, the rule and style modules, the models, the order
checker and the degenerate-family examples), and for the definitions of the models. Run
`lake env lean AxiomCheck.lean`; every line should say "does not depend on any axioms", except the
declarations listed in tests/expected_axiom_users.txt (docs/VERIFICATION.md says why).

Files are found by globbing PM/**/*.lean, so a new file is covered without editing this script;
tests/test_axiomcheck_coverage.py checks that AxiomCheck.lean is what this script generates."""
import re, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
THM = r"(?:protected )?theorem ([\w.']+)"
DEF = r"(?:noncomputable )?(?:protected )?(?:def|abbrev) ([\w.]+)"


def files():
    """Every Lean file under PM/, in a fixed order."""
    return sorted(str(p.relative_to(root)) for p in (root / "PM").rglob("*.lean"))


def declared(text):
    """(full name, is theorem) of each public theorem and def of a file, with the enclosing namespaces
    (`namespace X` ... `end X`) prefixed, so `theorem and` inside `namespace ClsExpr` is `PM.ClsExpr.and`.
    A `mutual` block, like a section, opens no namespace but is closed by `end`; a name written
    `_root_.A.b` is `A.b` whatever the namespaces."""
    ns = []  # the open namespaces, sections and mutual blocks, innermost last; the last two are None
    for line in text.splitlines():
        if m := re.match(r"namespace ([\w.]+)\s*$", line):
            ns.append(m.group(1))
        elif re.match(r"(?:noncomputable )?section\b", line) or re.match(r"mutual\s*$", line):
            ns.append(None)
        elif re.match(r"end\b\s*[\w.]*\s*$", line):
            if ns:
                ns.pop()
        elif m := re.match(THM, line):
            yield full(ns, m.group(1)), True
        elif m := re.match(DEF, line):
            yield full(ns, m.group(1)), False


def full(ns, name):
    """The full name of `name` declared inside the namespaces `ns`."""
    if name.startswith("_root_."):
        return name.removeprefix("_root_.")
    return ".".join([n for n in ns if n] + [name])


def names():
    out = []
    for f in files():
        for name, thm in declared((root / f).read_text(encoding="utf-8")):
            local = name.removeprefix("PM.")
            if thm or "Model" in local or "model" in local.lower():
                full = name if name.startswith("PM.") else f"PM.{name}"
                if full not in out:
                    out.append(full)
    return out


def generate():
    out = ["-- Generated by scripts/gen_axiomcheck.py; run with `lake env lean AxiomCheck.lean`.", "import PM", ""]
    out += [f"#print axioms {n}" for n in names()]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = generate()
    (root / "AxiomCheck.lean").write_text(text, encoding="utf-8")
    print(text.count("#print axioms"), "names")
