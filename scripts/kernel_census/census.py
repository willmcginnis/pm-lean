def summary_cell(c, col, key):
    if key is None:
        return "n/d"
    kind, f = key.split(":", 1)
    if kind == "d":
        rc = (c.get("recheck") or {}).get(col)
        if rc is None:
            return "—"
        if f == "_any":
            return cell(rc["unfoldedAnything"])
        return cell(rc["features"].get(f, {}).get("count", 0))
    feats = c["columns"][col]["features"]
    if f == "_natops":
        ops = [k.rsplit(".", 1)[1] for k in sorted(feats) if k.startswith("nat.op.")]
        return ", ".join(ops) or "·"
    if f == "_unsafe":
        return cell(sum(feats.get(k, {}).get("count", 0)
                        for k in ["def.unsafeSafety", "opaque.unsafeFlag", "ind.unsafeFlag"]))
    if f == "_reduce":
        return cell(sum(v["count"] for k, v in feats.items()
                        if k in ("const.Lean.ofReduceBool", "const.Lean.ofReduceNat",
                                 "const.Lean.trustCompiler", "const.Lean.reduceBool", "const.Lean.reduceNat")))
    return cell(feats.get(f, {}).get("count", 0))


def run(cmd, env=None):
    r = subprocess.run(cmd, cwd=ROOT, env=env, capture_output=True, text=True)
    return r.returncode, r.stdout + r.stderr


def build_targets():
    """The repository's modules the meta-program imports (`import Lean` is the toolchain's)."""
    mods = re.findall(r"^import\s+(\S+)", LEAN_FILE.read_text(encoding="utf-8"), re.M)
    return [m for m in mods if m.split(".")[0] != "Lean"]


def build():
    code, out = run(["lake", "build", *build_targets()])
    if code != 0:
        print(out)
        sys.exit("lake build failed: the census is not run")


def run_census(mode):
    WORK.mkdir(parents=True, exist_ok=True)
    out = WORK / f"census-{mode}.json"
    env = dict(os.environ, PM_CENSUS_MODE=mode, PM_CENSUS_OUT=str(out))
    code, text = run(["lake", "env", "lean", str(LEAN_FILE)], env)
    if code != 0:
        print(text)
        sys.exit("the census meta-program failed")
    return json.loads(out.read_text(encoding="utf-8"))


