def expected_axiom_users():
    out = {}
    for line in EXPECTED_AXIOMS.read_text(encoding="utf-8").splitlines():
        line = line.split("#")[0].split()
        if line:
            out[line[0]] = sorted(line[1:])
    return out


def is_user_facing(name):
    """A name AllAxioms.lean reports: under `PM` (or private in a PM module), no internal component."""
    if name.startswith("_private.PM."):
        return True
    return name.startswith("PM.") and not any(p.startswith("_") for p in name.split("."))


def axiom_users_by_decl(c):
    out = {}
    for a, v in c["axiomUsers"].items():
        for u in v["repository"]:
            out.setdefault(u, []).append(a)
    return {u: sorted(a) for u, a in out.items()}


def ratchet_features(c):
    return sorted(f"{k} {f}" for k in RATCHET_COLUMNS for f in c["columns"][k]["features"])


def read_expected():
    return sorted(l.split("#")[0].strip() for l in EXPECTED.read_text(encoding="utf-8").splitlines()
                  if l.split("#")[0].strip())


def write_expected(feats):
    head = ["# The kernel features of the PM derivations (docs/KERNEL_CENSUS.md), one per line: the column",
            "# of the census and the feature. tests/test_kernel_census.py fails if the census finds another",
            "# set; a new feature is added here only deliberately, saying why in the commit, and a feature",
            "# that disappears is removed. Rewrite with",
            "#   python3 scripts/kernel_census/census.py --ratchet --update"]
    EXPECTED.write_text("\n".join(head + feats) + "\n", encoding="utf-8")


def check_ratchet(c):
    """Problems found by the ratchet, as lines; empty if none."""
    problems = []
    got, exp = set(ratchet_features(c)), set(read_expected())
    for x in sorted(got - exp):
        col, f = x.split(" ", 1)
        v = c["columns"][col]["features"][f]
        where = " → ".join(v.get("path", [])) or ", ".join(v["examples"])
        problems.append(f"new kernel feature: {x} ({v['count']} declarations; {where})")
    for x in sorted(exp - got):
        problems.append(f"feature no longer used (remove it from {EXPECTED.relative_to(ROOT)}): {x}")
    users = {u: a for u, a in axiom_users_by_decl(c).items() if is_user_facing(u)}
    exp = expected_axiom_users()
    for k in sorted(set(users) | set(exp)):
        if users.get(k) != exp.get(k):
            problems.append(f"axiom user {k}: the census finds {users.get(k)}, "
                            f"{EXPECTED_AXIOMS.relative_to(ROOT)} lists {exp.get(k)}")
    return problems


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--ratchet", action="store_true")
    ap.add_argument("--update", action="store_true")
    ap.add_argument("--reuse", action="store_true",
                    help="with --write or --check: the last full run's results, without running Lean")
    a = ap.parse_args()
    if not a.reuse:
        build()
    if a.ratchet:
        c = run_census("ratchet")
        if a.update:
            write_expected(ratchet_features(c))
            print(f"wrote {EXPECTED.relative_to(ROOT)}")
        problems = check_ratchet(c)
        for p in problems:
            print(p)
        print(f"kernel census ratchet: {len(ratchet_features(c))} features of the PM derivations, "
              f"{len(problems)} problems; static walk {c['timing']['staticMs']} ms")
        sys.exit(1 if problems else 0)
    merged = WORK / "census-merged.json"
    if a.reuse:
        c = json.loads(merged.read_text(encoding="utf-8"))
    else:
        c = run_census("full")
        c = merge_examples(c, examples_pass())
        merged.write_text(json.dumps(c, indent=1), encoding="utf-8")
    text = report(c)
    doc = DOC.read_text(encoding="utf-8")
    i, j = doc.index(BEGIN), doc.index(END) + len(END) + 1
    if a.write:
        DOC.write_text(doc[:i] + text + doc[j:], encoding="utf-8")
        print(f"wrote {DOC.relative_to(ROOT)}")
    elif a.check:
        if doc[i:j] != text:
            sys.exit(f"{DOC.relative_to(ROOT)} differs from the census: run census.py --write")
        print("the doc agrees with the census")
    else:
        print(text)
    problems = check_ratchet(c)
    for p in problems:
        print(p)
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    main()
